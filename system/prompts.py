def build_meeting_prompt(
    domain: str = "", attendees_context: str = "",
    enable_extra1: bool = False, enable_extra2: bool = False,
) -> str:
    """
    بيبني برومبت "خد نوتس" (توثيق اجتماع، لكل مقطع لوحده) حسب مجال
    الاجتماع - نفس فكرة build_explain_prompt بتاعة المحاضرات بالظبط.

    domain: فاضي أو "" = السلوك الافتراضي (MEETING_NOTES_PROMPT زي ما
    هو، بدون أي تخصيص مجال).

    attendees_context: نص جاهز بأسماء/أدوار الحاضرين (أو فاضي لو مفيش
    حد اتسجّل) - بيتحط كسياق مساعد بس، مش تمييز أصوات حقيقي.

    enable_extra1/enable_extra2: الخيارين الإضافيين الخاصين بمجال
    الاجتماع ده (الـ checkboxes الاختيارية) - افتراضيًا الاتنين False.
    """
    domain = (domain or "").strip()

    if not domain:
        base = MEETING_NOTES_PROMPT
    else:
        profile = MEETING_SUBJECT_PROFILES.get(domain) or _other_meeting_profile(domain)
        focus_lines = "\n".join(
            f"- {f}" for f in (profile["focus1"], profile.get("focus2", "")) if f
        )
        # نفس هيكل MEETING_NOTES_PROMPT بالظبط، بس بـ header مخصص للمجال
        # ونقاط تركيز إضافية محقونة بعد الأقسام مباشرة.
        base = MEETING_NOTES_PROMPT.replace(
            "أنت مساعد توثيق اجتماعات محترف. هدفك",
            f"أنت مساعد توثيق اجتماعات محترف. {profile['header']}\n\nهدفك",
            1,
        )
        base = base.replace(
            "قاعدة الأسماء (صارمة",
            f"نقاط تركيز خاصة بمجال الاجتماع ده:\n{focus_lines}\n\n"
            "قاعدة الأسماء (صارمة",
            1,
        )

    if attendees_context:
        base = (
            f"الحاضرين المعروفين في الاجتماع ده (سياق مساعد بس - مش "
            f"تمييز أصوات، ومجرد وجود اسم هنا مش دليل إنه قال حاجة):\n"
            f"{attendees_context}\n\n"
            + base
        )

    addendum = _meeting_optional_addendum(domain, enable_extra1, enable_extra2)
    return base + addendum if addendum else base


