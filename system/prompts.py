def _meeting_optional_addendum(domain: str, enable_extra1: bool, enable_extra2: bool) -> str:
    if not domain or domain not in _MEETING_EXTRA_OPTIONS:
        return ""
    extra1, extra2 = _MEETING_EXTRA_OPTIONS[domain]
    parts = []
    if enable_extra1:
        parts.append(f"- {extra1}")
    if enable_extra2:
        parts.append(f"- {extra2}")
    if not parts:
        return ""
    return (
        "\n\n--- إضافي (مفعّل بمعرفة المستخدم لمجال الاجتماع ده) ---\n\n"
        + "\n".join(parts)
    )


